char *si_font_alphanum_get(char c, int *width)
{
    *width = 5;
    
    if (c >= 'A' && c <= 'Z') return (char *)si_font_alphanum[c - 'A' + 1];
    if (c >= '0' && c <= '9') return (char *)si_font_alphanum[c - '0' + 27];
    if (c == ' ') return (char *)si_font_alphanum[0];
    if (c == '<') return (char *)si_font_alphanum[37];
    if (c == '>') return (char *)si_font_alphanum[38];
    if (c == '-') return (char *)si_font_alphanum[39];
    if (c == '*') return (char *)si_font_alphanum[40];
    if (c == '?') return (char *)si_font_alphanum[41];
    if (c == '=') return (char *)si_font_alphanum[42];
    
    return (char *)si_font_alphanum[0];
}

